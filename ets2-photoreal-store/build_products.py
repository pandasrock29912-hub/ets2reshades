#!/usr/bin/env python3
"""
Build the customer-facing product zips from the preset source folder.

IMPORTANT (licensing): these zips contain ONLY files authored by us:
  - the .ini presets (our tuning values)
  - Textures/lut.png (generated by our generate_lut.py)
  - our documentation and our LUT script

They deliberately contain NO third-party .fx shader files. Several of the
shaders the presets drive (iMMERSE/METEOR, qUINT, AstrayFX, brussell) are
under "all rights reserved" / non-commercial licenses, so we never
redistribute them. Customers install ReShade + the shader packages
themselves from the official installer (instructions are inside the zip).

Usage:
    python3 build_products.py            # build both zips
    python3 build_products.py --src DIR  # override preset source dir
"""
import argparse
import io
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.abspath(os.path.join(HERE, "..", "ETS2-Photoreal-Preset"))
OUT_DIR = os.path.join(HERE, "products")

# --- tiny helpers for files that only exist inside the zip -------------------
QUICKSTART_REGULAR = """ETS2 PHOTOREALISM - STANDARD EDITION
====================================

Thank you for your purchase. You keep these files forever.

WHAT'S IN HERE
  ETS2_Photorealism.ini        Tier 1 - lightest, best performance
  ETS2_Photorealism_MAX.ini    Tier 2 - full photoreal stack (recommended)
  Textures/lut.png             The film grade (required - keep this file!)
  README.md                    Full documentation
  Tools/generate_lut.py        Recreate the LUT from source if you want

INSTALL (5 minutes)
  1. Install ReShade into ETS2.exe. Tick ALL shader packages in the
     installer (they are free and open source).
  2. Copy BOTH .ini files into your ETS2 game folder (next to ETS2.exe).
  3. Copy the Textures folder into your ETS2 game folder too, so you end
     up with:  <ETS2>/Textures/lut.png
  4. Launch the game, press the ReShade overlay key (usually Home),
     pick ETS2_Photorealism_MAX.ini, done.

TIP
  Start with ETS2_Photorealism_MAX.ini. Drop to ETS2_Photorealism.ini
  only if you need more FPS.

Full tuning guide: see README.md
"""

QUICKSTART_PREMIUM = """ETS2 PHOTOREALISM - PREMIUM EDITION
====================================

Thank you for your purchase. You keep these files forever.

WHAT'S IN HERE
  ETS2_Premium.ini             Tier 3 - premium, no depth needed
  ETS2_Premium_Depth.ini       Tier 4 - premium + AO/haze/DOF (best)
  Textures/lut.png             The film grade (required - keep this file!)
  README_PREMIUM.md            Premium tuning & depth calibration guide
  README.md                    Standard-tier documentation
  Tools/generate_lut.py        Recreate the LUT from source if you want

INSTALL (5 minutes)
  1. Install ReShade into ETS2.exe. Tick ALL shader packages in the
     installer (they are free and open source).
  2. Copy BOTH .ini files into your ETS2 game folder (next to ETS2.exe).
  3. Copy the Textures folder into your ETS2 game folder too, so you end
     up with:  <ETS2>/Textures/lut.png
  4. Launch the game, press the ReShade overlay key (usually Home),
     pick ETS2_Premium.ini first (works everywhere, no setup).

TIER 4 (depth) - one-time setup
  ETS2_Premium_Depth.ini needs the depth buffer. See the
  "Depth calibration" section of README_PREMIUM.md (about 5 minutes).
  If you'd rather skip that, just use ETS2_Premium.ini - it's excellent.

Full tuning guide: see README_PREMIUM.md
"""

PRODUCTS = {
    "ETS2_Photoreal_Standard.zip": {
        "desc": "Standard edition: Tiers 1-2",
        "include": [
            "ETS2_Photorealism.ini",
            "ETS2_Photorealism_MAX.ini",
            os.path.join("Textures", "lut.png"),
            "README.md",
            os.path.join("Tools", "generate_lut.py"),
        ],
        "quickstart": QUICKSTART_REGULAR,
    },
    "ETS2_Photoreal_Premium.zip": {
        "desc": "Premium edition: Tiers 3-4",
        "include": [
            "ETS2_Premium.ini",
            "ETS2_Premium_Depth.ini",
            os.path.join("Textures", "lut.png"),
            "README_PREMIUM.md",
            "README.md",
            os.path.join("Tools", "generate_lut.py"),
        ],
        "quickstart": QUICKSTART_PREMIUM,
    },
}

FORBIDDEN_EXT = (".fx", ".fxh", ".hlsl", ".cso", ".dll", ".exe")


def build(src: str) -> int:
    if not os.path.isdir(src):
        print(f"ERROR: preset source dir not found: {src}", file=sys.stderr)
        return 2
    os.makedirs(OUT_DIR, exist_ok=True)
    failures = 0
    for zipname, spec in PRODUCTS.items():
        outpath = os.path.join(OUT_DIR, zipname)
        with zipfile.ZipFile(outpath, "w", zipfile.ZIP_DEFLATED) as zf:
            # quick start first so it sorts to the top in most file browsers
            zf.writestr("START_HERE.txt", spec["quickstart"])
            for rel in spec["include"]:
                fpath = os.path.join(src, rel)
                if not os.path.isfile(fpath):
                    print(f"  !! MISSING: {rel}  (needed for {zipname})")
                    failures += 1
                    continue
                if rel.lower().endswith(FORBIDDEN_EXT):
                    # never ship third-party shader source / binaries
                    print(f"  !! REFUSING to ship shader file: {rel}")
                    failures += 1
                    continue
                # store under its relative path so Textures/lut.png lands right
                zf.write(fpath, rel.replace(os.sep, "/"))
        size = os.path.getsize(outpath)
        n = len(zipfile.ZipFile(outpath).namelist())
        print(f"  OK  {zipname:38s} {size/1024:8.1f} KB  ({n} files)")
    print()
    print("NOTE: zips contain only our own files. No third-party .fx shaders are")
    print("      redistributed; customers install those via the ReShade installer.")
    return 1 if failures else 0


def main():
    ap = argparse.ArgumentParser(description="Build customer product zips.")
    ap.add_argument("--src", default=DEFAULT_SRC, help="preset source directory")
    a = ap.parse_args()
    print(f"Building products from: {a.src}")
    print(f"Output directory:       {OUT_DIR}\n")
    raise SystemExit(build(os.path.abspath(a.src)))


if __name__ == "__main__":
    main()
